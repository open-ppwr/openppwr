import { readFile, writeFile } from 'node:fs/promises';

const lockfilePath = 'package-lock.json';
const outputPath = 'docs/audit/THIRD_PARTY_LICENSE_INVENTORY.md';

const reviewedOverrides = new Map([
  ['busboy@1.6.0', { license: 'MIT', evidence: 'package-supplied LICENSE and package.json licenses field' }],
  ['png-js@1.1.0', { license: 'MIT', evidence: 'package-supplied LICENSE' }],
  ['streamsearch@1.1.0', { license: 'MIT', evidence: 'package-supplied LICENSE and package.json licenses field' }],
]);

// Every expression here has been reviewed against how the package is actually used. The set is
// deliberately small: an unreviewed licence stops the build rather than being assumed compatible.
const reviewedLicenseExpressions = new Set([
  '0BSD',
  'Apache-2.0',
  'BSD-3-Clause',
  'ISC',
  'MIT',
  '(MIT AND Zlib)',
  'LicenseRef-DejaVu-Fonts',
  // MPL-2.0 is weak copyleft at file level. It enters this project only through axe-core, a
  // development dependency used by the accessibility gate: it is never imported by the application,
  // never bundled, and never present in the published image or the Apache-2.0 distribution. Reviewed
  // and accepted on 2026-07-29 on that basis. A future runtime dependency under MPL-2.0 would be a
  // different question and must be reviewed separately rather than inheriting this decision.
  'MPL-2.0',
]);

function packageName(path) {
  const normalized = path.replaceAll('\\', '/');
  let relative = normalized.startsWith('node_modules/')
    ? normalized.slice('node_modules/'.length)
    : normalized;
  const nestedMarker = '/node_modules/';
  if (relative.includes(nestedMarker)) {
    relative = relative.slice(relative.lastIndexOf(nestedMarker) + nestedMarker.length);
  }
  return relative;
}

function normalizedLicense(name, version, declaredLicense) {
  const key = `${name}@${version}`;
  const override = reviewedOverrides.get(key);
  if (override) return override.license;
  if (name === 'dejavu-fonts-ttf' && version === '2.37.3') return 'LicenseRef-DejaVu-Fonts';
  return declaredLicense;
}

function renderInventory(lockfile) {
  if (!lockfile.packages || typeof lockfile.packages !== 'object') {
    throw new Error('package-lock.json has no packages inventory');
  }

  const inventory = new Map();
  for (const [path, metadata] of Object.entries(lockfile.packages)) {
    if (!path.includes('node_modules/') || metadata.link) continue;
    const name = packageName(path);
    const version = metadata.version;
    if (!name || !version) throw new Error(`incomplete package metadata at ${path}`);

    const key = `${name}@${version}`;
    const declaredLicense = metadata.license || '';
    const license = normalizedLicense(name, version, declaredLicense);
    if (!license) throw new Error(`unresolved license metadata: ${key}`);
    if (!reviewedLicenseExpressions.has(license)) {
      throw new Error(`unreviewed license expression: ${key} (${license})`);
    }

    const existing = inventory.get(key) || {
      name,
      version,
      license,
      production: false,
      optional: false,
    };
    if (existing.license !== license) throw new Error(`conflicting licenses: ${key}`);
    if (!metadata.dev) existing.production = true;
    if (metadata.optional) existing.optional = true;
    inventory.set(key, existing);
  }

  const rows = [...inventory.values()].sort(
    (left, right) => left.name.localeCompare(right.name) || left.version.localeCompare(right.version),
  );
  const productionCount = rows.filter((row) => row.production).length;
  const developmentCount = rows.length - productionCount;
  const licenseCounts = new Map();
  for (const row of rows) licenseCounts.set(row.license, (licenseCounts.get(row.license) || 0) + 1);

  const lines = [
    '# Third-party license inventory',
    '',
    '<!-- Generated by scripts/release/generate-third-party-inventory.mjs. Do not edit manually. -->',
    '',
    'Status: release-candidate npm metadata inventory; final package/image license-file reconciliation and owner/legal approval remain required.',
    '',
    `Source: \`package-lock.json\` package metadata. Unique external package versions: ${rows.length} ` +
      `(${productionCount} production, ${developmentCount} development-only).`,
    '',
    'Lockfile omissions for `busboy@1.6.0`, `png-js@1.1.0` and `streamsearch@1.1.0` are normalized to MIT from their package-supplied license files. `dejavu-fonts-ttf@2.37.3` is normalized to `LicenseRef-DejaVu-Fonts`; required Bitstream Vera and Arev terms are reproduced in `THIRD_PARTY_NOTICES.md`.',
    '',
    'This inventory records npm lockfile metadata plus the explicit overrides below. It is not a legal compatibility determination. It does not relicense third-party software or replace upstream license files shipped with installed dependencies. The release image preserves installed production package distributions; final review must reconcile their license/NOTICE files and runtime-base components with the image SBOM.',
    '',
    '## Summary',
    '',
    '| License expression | Package versions |',
    '| --- | ---: |',
    ...[...licenseCounts.entries()]
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([license, count]) => `| ${license} | ${count} |`),
    '',
    '## Packages',
    '',
    '| Package | Version | Scope | License |',
    '| --- | --- | --- | --- |',
    ...rows.map((row) => {
      const scope = row.production ? (row.optional ? 'production (optional)' : 'production') : 'development-only';
      return `| ${row.name} | ${row.version} | ${scope} | ${row.license} |`;
    }),
    '',
    '## Reviewed metadata overrides',
    '',
    ...[...reviewedOverrides.entries()].map(([key, value]) => `- \`${key}\`: ${value.license}; ${value.evidence}.`),
    '',
  ];

  return lines.join('\n');
}

const lockfile = JSON.parse(await readFile(lockfilePath, 'utf8'));
const expected = renderInventory(lockfile);
if (process.argv.includes('--check')) {
  const actual = await readFile(outputPath, 'utf8').catch(() => '');
  if (actual.replaceAll('\r\n', '\n') !== expected) {
    console.error(`THIRD_PARTY_INVENTORY_FAIL stale_or_missing=${outputPath}`);
    process.exitCode = 1;
  } else {
    console.log(`THIRD_PARTY_INVENTORY_PASS file=${outputPath}`);
  }
} else {
  await writeFile(outputPath, expected, 'utf8');
  console.log(`THIRD_PARTY_INVENTORY_WRITTEN file=${outputPath}`);
}
